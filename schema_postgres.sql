-- PostgreSQL schema for Supabase.
-- Timestamps and is_active intentionally use the same text and 0/1 formats
-- as schema.sql so existing application values remain compatible.

CREATE TABLE IF NOT EXISTS students (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    student_id TEXT NOT NULL UNIQUE,
    email TEXT NOT NULL UNIQUE,
    department TEXT NOT NULL,
    year_level TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    is_active INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS admins (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS login_records (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER,
    student_code TEXT,
    student_name TEXT,
    attempted_identifier TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('success', 'failed')),
    ip_address TEXT,
    user_agent TEXT,
    note TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    edited_at TEXT,
    edited_by INTEGER,
    FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE SET NULL,
    FOREIGN KEY (edited_by) REFERENCES admins(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS admin_audit_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id INTEGER NOT NULL,
    action TEXT NOT NULL,
    target_table TEXT NOT NULL,
    target_id INTEGER,
    details TEXT NOT NULL,
    created_at TEXT NOT NULL,
    FOREIGN KEY (admin_id) REFERENCES admins(id)
);

CREATE TABLE IF NOT EXISTS events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    location TEXT NOT NULL,
    event_date TEXT NOT NULL,
    capacity INTEGER NOT NULL DEFAULT 50 CHECK (capacity > 0),
    created_by INTEGER,
    created_at TEXT NOT NULL,
    FOREIGN KEY (created_by) REFERENCES admins(id) ON DELETE SET NULL
);

ALTER TABLE public.events
    ADD COLUMN IF NOT EXISTS capacity INTEGER NOT NULL DEFAULT 50 CHECK (capacity > 0);

CREATE TABLE IF NOT EXISTS event_participations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id INTEGER NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    status TEXT NOT NULL CHECK (status IN ('registered', 'waitlisted', 'cancelled')),
    created_at TEXT NOT NULL,
    UNIQUE (event_id, student_id)
);

CREATE INDEX IF NOT EXISTS idx_login_records_student ON login_records(student_id);
CREATE INDEX IF NOT EXISTS idx_login_records_created ON login_records(created_at);
CREATE INDEX IF NOT EXISTS idx_login_records_status_created
    ON login_records(status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_login_records_identifier_created
    ON login_records(lower(attempted_identifier), created_at DESC);
CREATE INDEX IF NOT EXISTS idx_admin_audit_logs_created
    ON admin_audit_logs(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_events_event_date
    ON events(event_date);
CREATE INDEX IF NOT EXISTS idx_event_participations_event_status
    ON event_participations(event_id, status, created_at);
