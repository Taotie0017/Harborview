CREATE OR REPLACE FUNCTION join_event(p_event_id INTEGER, p_student_id INTEGER)
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    event_capacity INTEGER;
    current_status TEXT;
    registered_count INTEGER;
    next_status TEXT;
BEGIN
    SELECT capacity INTO event_capacity FROM events WHERE id = p_event_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Event not found';
    END IF;

    SELECT status INTO current_status
    FROM event_participations
    WHERE event_id = p_event_id AND student_id = p_student_id;
    IF current_status IN ('registered', 'waitlisted') THEN
        RETURN current_status;
    END IF;

    SELECT COUNT(*) INTO registered_count
    FROM event_participations
    WHERE event_id = p_event_id AND status = 'registered';
    next_status := CASE WHEN registered_count < event_capacity THEN 'registered' ELSE 'waitlisted' END;

    INSERT INTO event_participations (event_id, student_id, status, created_at)
    VALUES (p_event_id, p_student_id, next_status, CURRENT_TIMESTAMP::TEXT)
    ON CONFLICT (event_id, student_id)
    DO UPDATE SET status = EXCLUDED.status, created_at = EXCLUDED.created_at;
    RETURN next_status;
END;
$$;

CREATE OR REPLACE FUNCTION cancel_event_registration(p_event_id INTEGER, p_student_id INTEGER)
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    prior_status TEXT;
    event_capacity INTEGER;
    registered_count INTEGER;
    next_student_id INTEGER;
BEGIN
    SELECT capacity INTO event_capacity FROM events WHERE id = p_event_id FOR UPDATE;
    IF NOT FOUND THEN
        RETURN 'not_found';
    END IF;

    SELECT status INTO prior_status
    FROM event_participations
    WHERE event_id = p_event_id AND student_id = p_student_id;
    IF prior_status IS NULL OR prior_status = 'cancelled' THEN
        RETURN 'not_registered';
    END IF;

    UPDATE event_participations SET status = 'cancelled'
    WHERE event_id = p_event_id AND student_id = p_student_id;

    IF prior_status = 'registered' THEN
        SELECT COUNT(*) INTO registered_count
        FROM event_participations
        WHERE event_id = p_event_id AND status = 'registered';
        IF registered_count < event_capacity THEN
            SELECT student_id INTO next_student_id
            FROM event_participations
            WHERE event_id = p_event_id AND status = 'waitlisted'
            ORDER BY created_at, id
            LIMIT 1
            FOR UPDATE;
            IF next_student_id IS NOT NULL THEN
                UPDATE event_participations SET status = 'registered'
                WHERE event_id = p_event_id AND student_id = next_student_id;
            END IF;
        END IF;
    END IF;
    RETURN 'cancelled';
END;
$$;

REVOKE ALL ON FUNCTION join_event(INTEGER, INTEGER) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION cancel_event_registration(INTEGER, INTEGER) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION join_event(INTEGER, INTEGER) TO service_role;
GRANT EXECUTE ON FUNCTION cancel_event_registration(INTEGER, INTEGER) TO service_role;

